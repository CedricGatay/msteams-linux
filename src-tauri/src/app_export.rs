//! Package a prebuilt runtime; never compile on the end user's machine or copy
//! profile/Keychain data. All personalized output is outside the source checkout.
use crate::configuration::{self, AppConfig, CONFIG_RESOURCE};
use serde::Serialize;
#[cfg(test)]
use std::path::PathBuf;
use std::{path::Path, process::Command};

#[derive(Serialize)]
pub struct ExportedApp {
    pub path: String,
    pub name: String,
    pub identifier: String,
    pub profile_id: String,
}

fn copy_tree(
    source: &Path,
    destination: &Path,
    count: &mut usize,
    bytes: &mut u64,
) -> Result<(), String> {
    if *count > 4096 || *bytes > 512 * 1024 * 1024 {
        return Err("Runtime template is too large".into());
    }
    let metadata =
        std::fs::symlink_metadata(source).map_err(|_| "Cannot inspect runtime template")?;
    if metadata.file_type().is_symlink() {
        return Err("Symlinked templates are not supported".into());
    }
    if metadata.is_dir() {
        std::fs::create_dir(destination).map_err(|_| "Cannot create staged application")?;
        for entry in std::fs::read_dir(source).map_err(|_| "Cannot read runtime template")? {
            let entry = entry.map_err(|_| "Cannot read runtime template entry")?;
            *count += 1;
            copy_tree(
                &entry.path(),
                &destination.join(entry.file_name()),
                count,
                bytes,
            )?;
        }
    } else if metadata.is_file() {
        *bytes += metadata.len();
        if *bytes > 512 * 1024 * 1024 {
            return Err("Runtime template is too large".into());
        }
        std::fs::copy(source, destination).map_err(|_| "Cannot copy runtime template")?;
        std::fs::set_permissions(destination, metadata.permissions())
            .map_err(|_| "Cannot preserve executable permissions")?;
    } else {
        return Err("Unsupported template file type".into());
    }
    Ok(())
}

fn dictionary(path: &Path) -> Result<plist::Dictionary, String> {
    plist::Value::from_file(path)
        .map_err(|_| "Cannot read bundle metadata")?
        .into_dictionary()
        .ok_or_else(|| "Invalid bundle metadata".into())
}

fn existing_identity(destination: &Path) -> Result<Option<AppConfig>, String> {
    if !destination.exists() {
        return Ok(None);
    }
    if std::fs::symlink_metadata(destination)
        .map_err(|_| "Cannot inspect output")?
        .file_type()
        .is_symlink()
    {
        return Err("Cannot replace a symlinked application".into());
    }
    let config_path = destination.join("Contents/Resources").join(CONFIG_RESOURCE);
    let resolved = config_path
        .canonicalize()
        .map_err(|_| "Only an existing generated app can be updated")?;
    if !resolved.starts_with(
        destination
            .canonicalize()
            .map_err(|_| "Invalid output application")?,
    ) {
        return Err("Generated configuration must be inside its application".into());
    }
    let config = AppConfig::read(&resolved)?;
    if !config.generated || config.identifier.is_none() || config.profile_id.is_none() {
        return Err(
            "Refusing to overwrite an application not generated by this configurator".into(),
        );
    }
    let info = dictionary(&destination.join("Contents/Info.plist"))?;
    if info
        .get("CFBundleIdentifier")
        .and_then(plist::Value::as_string)
        != config.identifier.as_deref()
    {
        return Err("Existing application identity is inconsistent".into());
    }
    #[cfg(target_os = "macos")]
    {
        use objc2_app_kit::NSRunningApplication;
        use objc2_foundation::NSString;
        if !NSRunningApplication::runningApplicationsWithBundleIdentifier(&NSString::from_str(
            config.identifier(),
        ))
        .is_empty()
        {
            return Err("Quit the generated application before updating it".into());
        }
    }
    Ok(Some(config))
}

fn sign_and_verify(path: &Path, identifier: &str, entitlement_file: &Path) -> Result<(), String> {
    let signed = Command::new("/usr/bin/codesign")
        .args([
            "--force",
            "--sign",
            "-",
            "--identifier",
            identifier,
            "--options",
            "runtime",
            "--timestamp=none",
            "--entitlements",
        ])
        .arg(entitlement_file)
        .arg(path)
        .output()
        .map_err(|_| "Cannot run macOS codesign")?;
    if !signed.status.success() {
        return Err("macOS could not sign the generated app".into());
    }
    let verified = Command::new("/usr/bin/codesign")
        .args(["--verify", "--deep", "--strict"])
        .arg(path)
        .output()
        .map_err(|_| "Cannot verify generated app")?;
    if !verified.status.success() {
        return Err("Generated app signature verification failed".into());
    }
    Ok(())
}

pub fn export(
    config: AppConfig,
    template: &Path,
    destination: &Path,
) -> Result<ExportedApp, String> {
    export_with_signer(config, template, destination, sign_and_verify)
}

fn export_with_signer(
    config: AppConfig,
    template: &Path,
    destination: &Path,
    signer: impl FnOnce(&Path, &str, &Path) -> Result<(), String>,
) -> Result<ExportedApp, String> {
    let destination = configuration::ensure_private_destination(destination)?;
    if destination.extension().and_then(|v| v.to_str()) != Some("app") {
        return Err("Output must be an .app bundle".into());
    }
    let template = template
        .canonicalize()
        .map_err(|_| "Runtime template is missing")?;
    if destination.starts_with(&template) || template.starts_with(&destination) {
        return Err("Output cannot contain or overwrite the runtime template".into());
    }
    let template_marker = std::fs::read(template.join("Contents/Resources/runtime-template.json"))
        .ok()
        .and_then(|bytes| serde_json::from_slice::<serde_json::Value>(&bytes).ok());
    if !template_marker.is_some_and(|value| {
        value["schema"] == 1 && value["engine"] == "msteams-tauri-configurable-runtime"
    }) {
        return Err(
            "Template does not support embedded runtime configuration; rebuild the runtime".into(),
        );
    }
    let existing = existing_identity(&destination)?;
    let mut config = config.export_identity(existing.as_ref());
    config.validate()?;
    let parent = destination.parent().ok_or("Invalid output directory")?;
    let scratch = parent.join(format!(".teams-export-{}", uuid::Uuid::new_v4().simple()));
    std::fs::create_dir(&scratch).map_err(|_| "Cannot create export staging directory")?;
    let staged = scratch.join("Application.app");
    let result = (|| {
        copy_tree(&template, &staged, &mut 0, &mut 0)?;
        let resources = staged.join("Contents/Resources");
        std::fs::create_dir_all(&resources).map_err(|_| "Cannot create app resources")?;
        let marker = resources.join(configuration::CONFIGURATOR_MARKER);
        if marker.exists() {
            std::fs::remove_file(marker).map_err(|_| "Cannot prepare runtime role")?;
        }
        let nested = resources.join("RuntimeTemplate.app");
        if nested.exists() {
            return Err("Use the runtime template, not the configurator bundle".into());
        }
        let bytes =
            serde_json::to_vec_pretty(&config).map_err(|_| "Cannot serialize app configuration")?;
        std::fs::write(resources.join(CONFIG_RESOURCE), bytes)
            .map_err(|_| "Cannot write embedded app settings")?;
        let info_path = staged.join("Contents/Info.plist");
        let mut info = dictionary(&info_path)?;
        let executable = info
            .get("CFBundleExecutable")
            .and_then(plist::Value::as_string)
            .ok_or("Runtime executable metadata missing")?;
        if executable.contains('/')
            || executable.contains('\\')
            || executable == "."
            || executable == ".."
            || !staged.join("Contents/MacOS").join(executable).is_file()
        {
            return Err("Invalid runtime executable".into());
        }
        for key in ["CFBundleName", "CFBundleDisplayName"] {
            info.insert(key.into(), plist::Value::String(config.name.clone()));
        }
        info.insert(
            "CFBundleIdentifier".into(),
            plist::Value::String(config.identifier().into()),
        );
        info.insert(
            "NSCameraUsageDescription".into(),
            plist::Value::String(format!("{} uses your camera for Teams calls.", config.name)),
        );
        info.insert(
            "NSMicrophoneUsageDescription".into(),
            plist::Value::String(format!(
                "{} uses your microphone for Teams calls.",
                config.name
            )),
        );
        plist::Value::Dictionary(info)
            .to_file_xml(&info_path)
            .map_err(|_| "Cannot write generated bundle metadata")?;
        let entitlements = scratch.join("runtime-entitlements.plist");
        std::fs::write(&entitlements, include_str!("../Entitlements.plist"))
            .map_err(|_| "Cannot prepare signing entitlements")?;
        signer(&staged, config.identifier(), &entitlements)?;
        let backup = scratch.join("Previous.app");
        if destination.exists() {
            std::fs::rename(&destination, &backup)
                .map_err(|_| "Cannot stage previous app for update")?;
        }
        if std::fs::rename(&staged, &destination).is_err() {
            if backup.exists() {
                let _ = std::fs::rename(&backup, &destination);
            }
            return Err("Cannot install generated app; previous app was retained".into());
        }
        Ok(ExportedApp {
            path: destination.to_string_lossy().into(),
            name: config.name.clone(),
            identifier: config.identifier().into(),
            profile_id: config.profile_id.clone().unwrap(),
        })
    })();
    // A failed rollback must never delete the only remaining previous bundle.
    if !(scratch.join("Previous.app").exists() && !destination.exists()) {
        let _ = std::fs::remove_dir_all(&scratch);
    }
    result
}

#[cfg(test)]
mod tests {
    use super::*;
    fn fixtures() -> (PathBuf, PathBuf) {
        let root = std::env::temp_dir().join(format!("teams-export-test-{}", uuid::Uuid::new_v4()));
        let template = root.join("Template.app");
        std::fs::create_dir_all(template.join("Contents/MacOS")).unwrap();
        std::fs::create_dir_all(template.join("Contents/Resources")).unwrap();
        std::fs::write(
            template.join("Contents/Resources/runtime-template.json"),
            include_bytes!("../../config/runtime-template.json"),
        )
        .unwrap();
        std::fs::write(
            template.join("Contents/MacOS/runtime"),
            b"synthetic-executable",
        )
        .unwrap();
        let mut info = plist::Dictionary::new();
        info.insert("CFBundleExecutable".into(), "runtime".into());
        info.insert("CFBundleIdentifier".into(), "com.example.template".into());
        plist::Value::Dictionary(info)
            .to_file_xml(template.join("Contents/Info.plist"))
            .unwrap();
        (root, template)
    }
    #[test]
    fn exports_isolated_apps_updates_identity_and_leaves_existing_untouched_on_sign_failure() {
        let (root, template) = fixtures();
        let target = root.join("Example.app");
        let one =
            export_with_signer(AppConfig::default(), &template, &target, |_, _, _| Ok(())).unwrap();
        let two =
            export_with_signer(AppConfig::default(), &template, &target, |_, _, _| Ok(())).unwrap();
        assert_eq!(one.identifier, two.identifier);
        assert_eq!(one.profile_id, two.profile_id);
        let prior = std::fs::read(target.join("Contents/Info.plist")).unwrap();
        assert!(
            export_with_signer(AppConfig::default(), &template, &target, |_, _, _| Err(
                "synthetic signing failure".into()
            ))
            .is_err()
        );
        assert_eq!(
            std::fs::read(target.join("Contents/Info.plist")).unwrap(),
            prior
        );
        assert!(!target
            .join("Contents/Resources")
            .join(configuration::CONFIGURATOR_MARKER)
            .exists());
        std::fs::remove_dir_all(root).unwrap();
    }
    #[test]
    fn refuses_unrelated_existing_apps_and_symlinked_templates() {
        let (root, template) = fixtures();
        let target = root.join("Other.app");
        std::fs::create_dir(&target).unwrap();
        assert!(
            export_with_signer(AppConfig::default(), &template, &target, |_, _, _| Ok(())).is_err()
        );
        #[cfg(unix)]
        {
            std::os::unix::fs::symlink(&template, template.join("Contents/Resources/cycle"))
                .unwrap();
            assert!(export_with_signer(
                AppConfig::default(),
                &template,
                &root.join("New.app"),
                |_, _, _| Ok(())
            )
            .is_err());
        }
        std::fs::remove_dir_all(root).unwrap();
    }
}
